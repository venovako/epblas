PROGRAM TXERBLA
  IMPLICIT NONE
  INTERFACE
     SUBROUTINE XERBLA(SRNAME, INFO)
       IMPLICIT NONE
       CHARACTER(LEN=*), INTENT(IN) :: SRNAME
       INTEGER, INTENT(IN) :: INFO
     END SUBROUTINE XERBLA
  END INTERFACE
  INTERFACE
     PURE FUNCTION XERRNO()
       IMPLICIT NONE
       INTEGER :: XERRNO
     END FUNCTION XERRNO
  END INTERFACE
  INTERFACE
     SUBROUTINE SET_BLAS_XERBLA(CB)
       IMPLICIT NONE
       ABSTRACT INTERFACE
          SUBROUTINE XERBLA_INTERFACE(SRNAME, INFO)
            IMPLICIT NONE
            CHARACTER(LEN=*), INTENT(IN) :: SRNAME
            INTEGER, INTENT(IN) :: INFO
          END SUBROUTINE XERBLA_INTERFACE
       END INTERFACE
       PROCEDURE(XERBLA_INTERFACE) :: CB
     END SUBROUTINE SET_BLAS_XERBLA
  END INTERFACE
  INTEGER :: E
  E = 1
  CALL XERBLA('XERBLA', E)
  E = XERRNO()
  PRINT *, E
  CALL SET_BLAS_XERBLA(NEWXER)
  CALL XERBLA('NEWXER', E)
CONTAINS
  SUBROUTINE NEWXER(SRNAME, INFO)
    IMPLICIT NONE
    CHARACTER(LEN=*), INTENT(IN) :: SRNAME
    INTEGER, INTENT(IN) :: INFO
    PRINT *, SRNAME, INFO
  END SUBROUTINE NEWXER
END PROGRAM TXERBLA
